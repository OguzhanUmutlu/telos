/// Client sends an interactive player command or debug action to server.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct C2sPlayerCommand {
    /// Command payload.
    pub command: PlayerCommandKind,
}

impl C2sPlayerCommand {
    /// Encodes into wire buffer.
    pub fn encode(&self, buf: &mut Vec<u8>) {
        match self.command {
            PlayerCommandKind::Damage(amt) => {
                buf.push(0);
                buf.extend_from_slice(&amt.to_le_bytes());
            }
            PlayerCommandKind::Heal(amt) => {
                buf.push(1);
                buf.extend_from_slice(&amt.to_le_bytes());
            }
            PlayerCommandKind::SetFood(food) => {
                buf.push(2);
                encode_varint(food, buf);
            }
            PlayerCommandKind::AddXp(pts) => {
                buf.push(3);
                encode_varint(pts, buf);
            }
            PlayerCommandKind::SetWeather(w) => {
                buf.push(4);
                buf.push(w);
            }
            PlayerCommandKind::TriggerLightning => {
                buf.push(5);
            }
            PlayerCommandKind::SpawnMob { mob_type, x, y, z } => {
                buf.push(6);
                buf.push(mob_type);
                buf.extend_from_slice(&x.to_le_bytes());
                buf.extend_from_slice(&y.to_le_bytes());
                buf.extend_from_slice(&z.to_le_bytes());
            }
            PlayerCommandKind::ClearMobs => {
                buf.push(7);
            }
            PlayerCommandKind::SetGameMode(mode) => {
                buf.push(8);
                buf.push(mode);
            }
            PlayerCommandKind::ApplyEffect {
                effect_id,
                duration_ticks,
                amplifier,
            } => {
                buf.push(9);
                buf.push(effect_id);
                encode_varint(duration_ticks, buf);
                buf.push(amplifier);
            }
            PlayerCommandKind::ClearEffects => {
                buf.push(10);
            }
            PlayerCommandKind::DrinkPotion { potion_type } => {
                buf.push(11);
                buf.push(potion_type);
            }
            PlayerCommandKind::DropItem { entire_stack } => {
                buf.push(12);
                buf.push(u8::from(entire_stack));
            }
            PlayerCommandKind::ShootBow { charge_ticks } => {
                buf.push(13);
                encode_varint(u32::from(charge_ticks), buf);
            }
        }
    }

    /// Decodes from wire buffer.
    #[allow(clippy::too_many_lines)]
    pub fn decode(cursor: &mut &[u8]) -> Result<Self> {
        if cursor.is_empty() {
            return Err(ProtocolError::UnexpectedEof);
        }
        let kind = cursor[0];
        *cursor = &cursor[1..];

        let command = match kind {
            0 => {
                if cursor.len() < 4 {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let amt = f32::from_le_bytes(cursor[..4].try_into().unwrap());
                *cursor = &cursor[4..];
                if !amt.is_finite() || amt < 0.0 {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.damage",
                        reason: "Amount must be finite and positive".to_string(),
                    });
                }
                PlayerCommandKind::Damage(amt)
            }
            1 => {
                if cursor.len() < 4 {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let amt = f32::from_le_bytes(cursor[..4].try_into().unwrap());
                *cursor = &cursor[4..];
                if !amt.is_finite() || amt < 0.0 {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.heal",
                        reason: "Amount must be finite and positive".to_string(),
                    });
                }
                PlayerCommandKind::Heal(amt)
            }
            2 => {
                let food = decode_varint(cursor)?;
                if food > 20 {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.food",
                        reason: "Food must be <= 20".to_string(),
                    });
                }
                PlayerCommandKind::SetFood(food)
            }
            3 => {
                let pts = decode_varint(cursor)?;
                if pts > 1_000_000 {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.xp",
                        reason: "XP points exceeds maximum limit".to_string(),
                    });
                }
                PlayerCommandKind::AddXp(pts)
            }
            4 => {
                if cursor.is_empty() {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let w = cursor[0];
                *cursor = &cursor[1..];
                if w > 2 {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.weather",
                        reason: "Weather kind must be <= 2".to_string(),
                    });
                }
                PlayerCommandKind::SetWeather(w)
            }
            5 => PlayerCommandKind::TriggerLightning,
            6 => {
                if cursor.len() < 25 {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let mob_type = cursor[0];
                let x = f64::from_le_bytes(cursor[1..9].try_into().unwrap());
                let y = f64::from_le_bytes(cursor[9..17].try_into().unwrap());
                let z = f64::from_le_bytes(cursor[17..25].try_into().unwrap());
                *cursor = &cursor[25..];
                if mob_type == 0 || mob_type > 3 {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.spawn_mob.mob_type",
                        reason: "Mob type must be 1..=3".to_string(),
                    });
                }
                if !x.is_finite() || !y.is_finite() || !z.is_finite() {
                    return Err(ProtocolError::InvalidValue {
                        field: "player_command.spawn_mob.pos",
                        reason: "Coordinates must be finite".to_string(),
                    });
                }
                PlayerCommandKind::SpawnMob { mob_type, x, y, z }
            }
            7 => PlayerCommandKind::ClearMobs,
            8 => {
                if cursor.is_empty() {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let mode = cursor[0];
                *cursor = &cursor[1..];
                PlayerCommandKind::SetGameMode(mode)
            }
            9 => {
                if cursor.is_empty() {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let effect_id = cursor[0];
                *cursor = &cursor[1..];
                let duration_ticks = decode_varint(cursor)?;
                if cursor.is_empty() {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let amplifier = cursor[0];
                *cursor = &cursor[1..];
                PlayerCommandKind::ApplyEffect {
                    effect_id,
                    duration_ticks,
                    amplifier,
                }
            }
            10 => PlayerCommandKind::ClearEffects,
            11 => {
                if cursor.is_empty() {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let potion_type = cursor[0];
                *cursor = &cursor[1..];
                PlayerCommandKind::DrinkPotion { potion_type }
            }
            12 => {
                if cursor.is_empty() {
                    return Err(ProtocolError::UnexpectedEof);
                }
                let entire_stack = cursor[0] != 0;
                *cursor = &cursor[1..];
                PlayerCommandKind::DropItem { entire_stack }
            }
            13 => {
                let charge_raw = decode_varint(cursor)?;
                if charge_raw > 1200 {
                    return Err(ProtocolError::InvalidValue {
                        field: "shoot_bow.charge_ticks",
                        reason: "Charge ticks must not exceed 1200".to_string(),
                    });
                }
                #[allow(clippy::cast_possible_truncation)]
                let charge_ticks = charge_raw as u16;
                PlayerCommandKind::ShootBow { charge_ticks }
            }
            other => {
                return Err(ProtocolError::InvalidDiscriminant {
                    enum_name: "PlayerCommandKind",
                    value: u32::from(other),
                });
            }
        };

        Ok(Self { command })
    }
}

