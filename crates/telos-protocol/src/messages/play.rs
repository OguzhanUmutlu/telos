/// Client responds to server heartbeat challenge to measure RTT.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct C2sKeepAlive {
    /// Opaque challenge ID matching server's keep-alive request.
    pub id: u64,
}

impl C2sKeepAlive {
    /// Encodes into wire buffer.
    pub fn encode(&self, buf: &mut Vec<u8>) {
        encode_varlong(self.id, buf);
    }

    /// Decodes from wire buffer.
    pub fn decode(cursor: &mut &[u8]) -> Result<Self> {
        let id = decode_varlong(cursor)?;
        Ok(Self { id })
    }
}

